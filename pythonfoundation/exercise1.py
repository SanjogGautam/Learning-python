'''Create a program that asks the user for two numbers and performs
addition, subtraction, multiplication, and division operations using
these numbers. Print the results of each operation.'''
num1= int(input("Enter the first number"))
num2= int(input("Enter the second number"))
#addition
sum= num1+num2
print(sum)
#subtraction
sub= num1-num2
print(sub)
#multiplication
mul= num1*num2
print(mul)
#division
div= num1/num2
print(div)
