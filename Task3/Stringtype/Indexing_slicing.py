x="Sanjog"
print(x[0])#first character
print(x[1])#second character
print(x[-1])#last character
print(x[0:3])#first three characters
print(x[2:])#from third character to end
print(x[:4])#from start to fourth character
print(x[::2])#every character with step of 2
print(x[::-1])#reverse the string
print(x[-1::-1])#reversse the string using negative indexing