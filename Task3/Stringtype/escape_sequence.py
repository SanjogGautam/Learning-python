# in python we use \ to insert illegal characters in a string like quotes in a string
print("He said, \"Hello!\"")#using escape sequence to insert double quotes in a string
'''\n-to insert a new line
\t-to insert a tab
\\-to insert a backslash 
\b-to insert a backspace'''
print("Hello\nWorld")
print("Hello\tWorld")
print("This is a backslash \\")
print("Hello\bWorld")#backspace will remove the last character of the string